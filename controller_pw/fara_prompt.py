"""Fara-1.5 prompt/coordinate constants, ported verbatim from microsoft/fara
(src/fara/agents/fara/_prompts.py, fara15_agent.py) for the Fara15 browser
action space ("fara_next_browser" mode, identity="fara_qwen35",
critical_points="fara-1.5").

fara_system_prompt.txt was generated by actually calling the official
get_computer_use_system_prompt() from a clone of microsoft/fara, not
hand-transcribed, so the tool schema JSON matches byte-for-byte.
"""

import math
from pathlib import Path

SYSTEM_PROMPT = (Path(__file__).parent / "fara_system_prompt.txt").read_text()

# Coordinate space the model emits [x, y] / pixels in. Fixed regardless of
# viewport or screenshot resolution -- see FaraBrowserComputerUse in
# _prompts.py (display_width_px == display_height_px == DISPLAY_SIZE).
DISPLAY_SIZE = 1000

VIEWPORT_WIDTH = 1440
VIEWPORT_HEIGHT = 900

# smart_resize() params from Fara15AgentConfig defaults (PATCH_SIZE=16,
# MERGE_SIZE=2, min_pixels=3136, max_pixels=12845056). Only affects the
# resolution of the image sent to the vision encoder, not the coordinate
# space above.
RESIZE_FACTOR = 16 * 2
MIN_PIXELS = 3136
MAX_PIXELS = 12845056

USER_MESSAGE = "Here is the next screenshot. Think about what to do next."


def _round_by_factor(number, factor):
    return round(number / factor) * factor


def _ceil_by_factor(number, factor):
    return math.ceil(number / factor) * factor


def _floor_by_factor(number, factor):
    return math.floor(number / factor) * factor


def smart_resize(height, width, factor=RESIZE_FACTOR, min_pixels=MIN_PIXELS, max_pixels=MAX_PIXELS):
    """Port of qwen_helpers/utils.py smart_resize. Returns (resized_height, resized_width)."""
    h_bar = max(factor, _round_by_factor(height, factor))
    w_bar = max(factor, _round_by_factor(width, factor))
    if h_bar * w_bar > max_pixels:
        beta = math.sqrt((height * width) / max_pixels)
        h_bar = _floor_by_factor(height / beta, factor)
        w_bar = _floor_by_factor(width / beta, factor)
    elif h_bar * w_bar < min_pixels:
        beta = math.sqrt(min_pixels / (height * width))
        h_bar = _ceil_by_factor(height * beta, factor)
        w_bar = _ceil_by_factor(width * beta, factor)
    return h_bar, w_bar


def scale_coordinate(coordinate, viewport_width=VIEWPORT_WIDTH, viewport_height=VIEWPORT_HEIGHT):
    """Map a [x, y] pair from Fara's DISPLAY_SIZE x DISPLAY_SIZE space to real viewport pixels."""
    x, y = coordinate
    return [x * viewport_width / DISPLAY_SIZE, y * viewport_height / DISPLAY_SIZE]


def scale_scroll_pixels(pixels, dimension):
    """Map a scroll amount from Fara's DISPLAY_SIZE space to real viewport pixels."""
    return int(pixels * dimension / DISPLAY_SIZE)
